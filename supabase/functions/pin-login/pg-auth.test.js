import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { describe, it } from "node:test";

const DB = "tlg_pin_auth_test";
const ROOT = new URL("../../migrations/", import.meta.url);

function psql(database, sql, { fail = false } = {}) {
  try {
    const out = execFileSync(
      "sudo",
      ["-u", "postgres", "psql", "-d", database, "-v", "ON_ERROR_STOP=1", "-q", "-t", "-A", "-c", sql],
      { encoding: "utf8" },
    );
    if (fail) throw new Error("expected SQL to fail: " + sql);
    // -q hides command tags (SET, BEGIN, GRANT). Keep the last row if one still leaks.
    const lines = out.trim().split("\n").map((line) => line.trim()).filter(Boolean);
    return lines.at(-1) ?? "";
  } catch (error) {
    if (!fail) throw error;
    return `${error.stderr || ""}\n${error.stdout || ""}\n${error.message}`;
  }
}

function psqlFile(database, filename) {
  execFileSync(
    "sudo",
    ["-u", "postgres", "psql", "-d", database, "-v", "ON_ERROR_STOP=1", "-f", new URL(filename, ROOT).pathname],
    { encoding: "utf8" },
  );
}

function setup() {
  psql("postgres", `select pg_terminate_backend(pid) from pg_stat_activity where datname = '${DB}' and pid <> pg_backend_pid()`);
  psql("postgres", `drop database if exists ${DB}`);
  psql("postgres", `create database ${DB}`);
  psql(DB, `
    do $$ begin create role anon nologin; exception when duplicate_object then null; end $$;
    do $$ begin create role authenticated nologin; exception when duplicate_object then null; end $$;
    do $$ begin create role service_role nologin bypassrls; exception when duplicate_object then alter role service_role bypassrls; end $$;
    create table public.crm_users (
      id integer generated by default as identity primary key,
      name text not null,
      pin text not null,
      role text not null default 'Sales',
      active boolean not null default true,
      created_at timestamptz default now()
    );
    insert into public.crm_users (name, pin, role, active) values
      ('Test Owner', '135790', 'Owner', true),
      ('Test Admin', '246801', 'Admin', true),
      ('Test Inactive', '192837', 'Sales', false);
    grant select, insert, update, delete, truncate, references, trigger on table public.crm_users to anon, authenticated;
    grant usage, select on sequence public.crm_users_id_seq to anon, authenticated;
  `);
  psqlFile(DB, "20261021120000_staff_pin_auth.sql");
}

describe("pgcrypto PIN migration", () => {
  it("hashes existing plaintext PINs, compares them, and keeps the column for rollback", () => {
    setup();
    const matched = psql(DB, `
      select count(*) from public.crm_users
      where pin_hash = extensions.crypt(pin, pin_hash)
        and pin_hash like '$2a$10$%'
        and token_version = 1
        and pin_set_at is not null
    `);
    assert.equal(matched, "3");
    assert.equal(psql(DB, "select pin from public.crm_users where name = 'Test Owner'"), "135790");

    const owner = JSON.parse(psql(DB, "select public.staff_check_pin(1, '135790')::text"));
    assert.equal(owner.ok, true);
    assert.equal(owner.role, "Owner");
    assert.equal(owner.pin, undefined);
    assert.equal(owner.pin_hash, undefined);

    const wrong = JSON.parse(psql(DB, "select public.staff_check_pin(1, '000000')::text"));
    assert.deepEqual(wrong, { ok: false });
    const inactive = JSON.parse(psql(DB, "select public.staff_check_pin(3, '192837')::text"));
    assert.deepEqual(inactive, { ok: false });

    const names = JSON.parse(psql(DB, "select public.staff_list_names()::text"));
    assert.deepEqual(names.map((row) => row.name), ["Test Admin", "Test Owner"]);
    assert.equal(JSON.stringify(names).includes("192837"), false);
    assert.equal(JSON.stringify(names).includes("pin"), false);

    psql(DB, "update public.crm_users set role = 'Sales' where id = 1");
    const reread = JSON.parse(psql(DB, "select public.staff_session(1)::text"));
    assert.equal(reread.role, "Sales");
    assert.equal(reread.active, true);
    assert.equal(reread.pin, undefined);

    const before = psql(DB, "select pin_hash from public.crm_users where id = 1");
    psqlFile(DB, "20261021120000_staff_pin_auth.sql");
    assert.equal(psql(DB, "select pin_hash from public.crm_users where id = 1"), before);

    const weak = JSON.parse(psql(DB, "select public.set_staff_pin(2, '123456')::text"));
    assert.equal(weak.ok, false);
    const duplicate = JSON.parse(psql(DB, "select public.set_staff_pin(2, '135790')::text"));
    assert.equal(duplicate.ok, false);
    const reset = JSON.parse(psql(DB, "select public.set_staff_pin(2, '918273')::text"));
    assert.equal(reset.ok, true);
    assert.equal(psql(DB, "select token_version::text from public.crm_users where id = 2"), "2");
    const resetCheck = JSON.parse(psql(DB, "select public.staff_check_pin(2, '918273')::text"));
    assert.equal(resetCheck.ok, true);
    const oldPin = JSON.parse(psql(DB, "select public.staff_check_pin(2, '246801')::text"));
    assert.equal(oldPin.ok, false);
  });

  it("lets anon read crm_users until the revoke migration, then denies the table, sequence, and functions", () => {
    setup();
    assert.equal(psql(DB, "set role anon; select count(*) from public.crm_users"), "3");

    psqlFile(DB, "20261021120100_crm_users_revoke_anon.sql");
    psqlFile(DB, "20261021120100_crm_users_revoke_anon.sql");

    assert.equal(psql(DB, "select relrowsecurity from pg_class where relname = 'crm_users'"), "t");
    assert.equal(psql(DB, "select count(*) from pg_policies where tablename = 'crm_users'"), "0");

    const deniedTable = psql(DB, "set role anon; select count(*) from public.crm_users", { fail: true });
    assert.match(deniedTable, /permission denied/i);
    const deniedAuth = psql(DB, "set role authenticated; select pin from public.crm_users", { fail: true });
    assert.match(deniedAuth, /permission denied/i);
    const deniedFn = psql(DB, "set role anon; select public.staff_check_pin(1, '135790')", { fail: true });
    assert.match(deniedFn, /permission denied/i);
    const deniedNames = psql(DB, "set role anon; select public.staff_list_names()", { fail: true });
    assert.match(deniedNames, /permission denied/i);
    const deniedAttempt = psql(DB, "set role anon; insert into public.staff_login_attempts (ip_hash, ok) values ('x', false)", { fail: true });
    assert.match(deniedAttempt, /permission denied/i);

    const inserted = psql(DB, `
      set role service_role;
      insert into public.staff_login_attempts (ip_hash, ok, crm_user_id, app)
      values ('abc', false, 1, 'lms')
      returning ip_hash
    `);
    assert.equal(inserted, "abc");

    const hidden = psql(DB, `
      begin;
      grant select on table public.crm_users to anon;
      set role anon;
      select count(*) from public.crm_users;
    `);
    assert.equal(hidden, "0");
  });
});
